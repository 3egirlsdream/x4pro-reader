#!/usr/bin/env python3
"""Generate the flash-resident WGS84 city catalogue from the vendored GeoNames subset."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'data/weather/cities.json').read_text())
lines = ['// Generated by scripts/build_weather_cities.py. GeoNames, CC BY 4.0.',
         '#include "WeatherStore.h"', '', 'namespace weather {', 'namespace {',
         'constexpr City CITIES[] = {']
seen = set()
for city in data['cities']:
    assert city['id'] not in seen
    seen.add(city['id'])
    assert -90 <= city['latitude'] <= 90 and -180 <= city['longitude'] <= 180
    lines.append('  {%d, %s, %s, %.5ff, %.5ff},' % (
        city['id'], json.dumps(city['province'], ensure_ascii=False),
        json.dumps(city['name'], ensure_ascii=False), city['latitude'], city['longitude']))
lines.extend(['};', '}', 'const City* cities() { return CITIES; }',
              'size_t cityCount() { return sizeof(CITIES) / sizeof(CITIES[0]); }',
              'const City* findCity(uint32_t id) {',
              '  for (const auto& city : CITIES) if (city.id == id) return &city;',
              '  return nullptr;', '}', '}  // namespace weather', ''])
(root / 'src/weather/WeatherCities.cpp').write_text('\n'.join(lines))
print(f'Generated {len(seen)} cities')
